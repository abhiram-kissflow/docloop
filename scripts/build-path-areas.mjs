// Turns the community→area mapping into a DIRECTORY PREFIX→area map, which is what B1 actually
// needs at runtime.
//
//   node --max-old-space-size=4096 scripts/build-path-areas.mjs
//
// WHY PREFIXES AND NOT FILES. B1 reacts to pushes, so it sees files as they are TODAY, while the
// graph is a snapshot from whenever it was last refreshed. A file-level map answers nothing about
// a file added since, which is precisely the file a push is most likely to contain. Directory
// structure is far more stable than file lists: a new module under components/web/src/form/ is
// forms-fields whether or not the graph has ever seen it.
//
// It is also ~200 lines of JSON instead of 45,000, so a human can read the whole thing and correct
// it — the same reason code-areas.json is a file rather than a table.
//
// ponytail: longest-prefix wins, votes decide ties, thin prefixes are dropped. Ceiling: a
// directory holding two unrelated features gets one label. Upgrade path: hand-edit the output —
// it is designed to be edited, and hand edits survive a regenerate only if you re-apply them,
// so keep corrections in the git history.

import fs from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const GRAPH = `${process.env.HOME}/.graphify-data/kissflow-cross-repo/graphify-out/graph.json`;

const MIN_VOTES = 6; // a prefix seen fewer times than this is an accident, not a pattern
const MIN_SHARE = 0.6; // the winning area must actually dominate, not merely lead
const MAX_DEPTH = 5;

const codeAreas = JSON.parse(fs.readFileSync(`${ROOT}/fixtures/code-areas.json`, 'utf8')).communities;
const graph = JSON.parse(fs.readFileSync(GRAPH, 'utf8'));

// prefix -> area -> votes
const votes = new Map();
let placed = 0;

for (const node of graph.nodes || []) {
  const file = node.source_file;
  const entry = codeAreas[node.community];
  if (!file || !entry || !entry.areas?.length) continue;
  placed++;

  const parts = String(file).split('/').filter(Boolean);
  parts.pop(); // the file itself; we are labelling directories
  for (let d = 1; d <= Math.min(parts.length, MAX_DEPTH); d++) {
    const prefix = parts.slice(0, d).join('/');
    if (!votes.has(prefix)) votes.set(prefix, new Map());
    const m = votes.get(prefix);
    for (const area of entry.areas) m.set(area, (m.get(area) || 0) + 1);
  }
}

// Resolve each prefix, then drop any whose parent already says the same thing — a child that adds
// no information is noise, and the runtime does longest-prefix matching anyway.
const resolved = new Map();
for (const [prefix, m] of votes) {
  const total = [...m.values()].reduce((a, b) => a + b, 0);
  const [top, n] = [...m.entries()].sort((a, b) => b[1] - a[1])[0];
  if (n < MIN_VOTES || n / total < MIN_SHARE) continue;
  resolved.set(prefix, { area: top, votes: n, share: Number((n / total).toFixed(2)) });
}

const out = {};
for (const [prefix, v] of [...resolved].sort((a, b) => a[0].localeCompare(b[0]))) {
  const parentPrefix = prefix.split('/').slice(0, -1).join('/');
  const parent = resolved.get(parentPrefix);
  if (parent && parent.area === v.area) continue; // parent covers it
  out[prefix] = v;
}

const path = `${ROOT}/fixtures/path-areas.json`;
fs.writeFileSync(path, JSON.stringify({
  _about: [
    'Directory prefix -> product area, for B1 (codebase staleness). A changed file is matched by',
    'LONGEST prefix. Generated by scripts/build-path-areas.mjs from fixtures/code-areas.json.',
    'Prefixes are used rather than file paths so files added after the last graph refresh still',
    'resolve. Hand edits are welcome and are the intended way to fix a wrong label.',
  ],
  prefixes: out,
}, null, 2) + '\n');

console.error(`[paths] ${placed} nodes placed, ${votes.size} prefixes seen, ${Object.keys(out).length} kept -> ${path}`);
